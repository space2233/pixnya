import { execFileSync, spawnSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import {
  mkdirSync,
  readFileSync,
  renameSync,
  statSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const comparablePath = (value) => {
  const resolved = path.resolve(value);
  return process.platform === "win32" ? resolved.toLowerCase() : resolved;
};

const exactlyOne = (values, description) => {
  if (values.length !== 1) {
    throw new Error(`Expected exactly one ${description}, found ${values.length}`);
  }
  return values[0];
};

const isDependencyKind = (dependency, kind) =>
  dependency.dep_kinds?.some((candidate) => candidate.kind === kind) === true;

const defaultIsFile = (value) => {
  try {
    return statSync(value).isFile();
  } catch {
    return false;
  }
};

const defaultIsDirectory = (value) => {
  try {
    return statSync(value).isDirectory();
  } catch {
    return false;
  }
};

export function planTauriAndroidGradleBridge(
  metadata,
  {
    appManifest,
    readText = (value) => readFileSync(value, "utf8"),
    isFile = defaultIsFile,
    isDirectory = defaultIsDirectory,
  },
) {
  const appPackage = exactlyOne(
    metadata.packages.filter(
      (candidate) => comparablePath(candidate.manifest_path) === comparablePath(appManifest),
    ),
    "src-tauri Cargo package in the Android-filtered locked graph",
  );
  if (metadata.resolve?.root !== appPackage.id) {
    throw new Error("Cargo metadata did not resolve src-tauri/Cargo.toml as the Android graph root");
  }

  const appNode = exactlyOne(
    metadata.resolve.nodes.filter((candidate) => candidate.id === appPackage.id),
    "src-tauri dependency node in the Android-filtered locked graph",
  );
  const packagesById = new Map(metadata.packages.map((candidate) => [candidate.id, candidate]));
  const dependencyPackage = (dependency) => {
    const resolved = packagesById.get(dependency.pkg);
    if (!resolved) {
      throw new Error(`Cargo metadata omitted direct dependency ${dependency.name}`);
    }
    return resolved;
  };

  const directNormalDependencies = appNode.deps.filter((candidate) =>
    isDependencyKind(candidate, null),
  );
  const directAndroidPlugins = directNormalDependencies
    .map(dependencyPackage)
    .filter((candidate) => candidate.name.startsWith("tauri-plugin-"));
  if (directAndroidPlugins.length > 0) {
    throw new Error(
      `Android Tauri plugin bridge generation is not covered: ${directAndroidPlugins
        .map((candidate) => candidate.name)
        .join(", ")}`,
    );
  }

  const tauriDependency = exactlyOne(
    directNormalDependencies.filter(
      (candidate) => dependencyPackage(candidate).name === "tauri",
    ),
    "direct normal Tauri dependency",
  );
  const tauriPackage = dependencyPackage(tauriDependency);
  if (
    tauriPackage.version !== "2.11.5" ||
    tauriPackage.name !== "tauri" ||
    tauriPackage.links !== "Tauri"
  ) {
    throw new Error("The locked Tauri Android module contract changed from tauri 2.11.5 / links=Tauri");
  }

  const tauriBuildDependency = exactlyOne(
    appNode.deps.filter(
      (candidate) =>
        isDependencyKind(candidate, "build") &&
        dependencyPackage(candidate).name === "tauri-build",
    ),
    "direct build-time tauri-build dependency",
  );
  const tauriBuildPackage = dependencyPackage(tauriBuildDependency);
  if (tauriBuildPackage.version !== "2.6.3") {
    throw new Error("The locked tauri-build Gradle bridge template changed from 2.6.3");
  }

  const tauriAndroid = path.join(path.dirname(tauriPackage.manifest_path), "mobile", "android");
  const tauriBuildTemplate = path.join(
    path.dirname(tauriBuildPackage.manifest_path),
    "src",
    "mobile.rs",
  );
  if (!isDirectory(tauriAndroid)) {
    throw new Error("The locked Tauri package has no mobile/android directory");
  }
  for (const requiredFile of [
    path.join(tauriAndroid, "build.gradle.kts"),
    path.join(tauriAndroid, "src", "main", "AndroidManifest.xml"),
    tauriBuildTemplate,
  ]) {
    if (!isFile(requiredFile)) {
      throw new Error(`The locked Tauri Android bridge source is incomplete: ${requiredFile}`);
    }
  }

  const tauriBuildSource = readText(tauriBuildTemplate);
  if (
    !tauriBuildSource.includes("generate_gradle_files") ||
    !tauriBuildSource.includes('implementation(\\"androidx.lifecycle:lifecycle-process:2.10.0\\")')
  ) {
    throw new Error("tauri-build 2.6.3 no longer has the reviewed lifecycle-process 2.10.0 template");
  }

  const header = "// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n";
  return {
    tauriVersion: tauriPackage.version,
    settings: `${header}include ':tauri-android'\nproject(':tauri-android').projectDir = new File(${JSON.stringify(
      tauriAndroid,
    )})\n`,
    appBuild: `${header}val implementation by configurations\ndependencies {\n  implementation("androidx.lifecycle:lifecycle-process:2.10.0")\n  implementation(project(":tauri-android"))\n}\n`,
  };
}

const writeAtomicallyIfChanged = (destination, contents) => {
  try {
    if (readFileSync(destination, "utf8") === contents) {
      return;
    }
  } catch (error) {
    if (error?.code !== "ENOENT") {
      throw error;
    }
  }

  mkdirSync(path.dirname(destination), { recursive: true });
  const temporary = `${destination}.${process.pid}.${randomUUID()}.tmp`;
  try {
    writeFileSync(temporary, contents, "utf8");
    renameSync(temporary, destination);
  } finally {
    try {
      unlinkSync(temporary);
    } catch (error) {
      if (error?.code !== "ENOENT") {
        throw error;
      }
    }
  }
};

const main = () => {
  const root = process.cwd();
  const appManifest = path.join(root, "src-tauri", "Cargo.toml");
  const androidProject = path.join(root, "src-tauri", "gen", "android");
  const settingsPath = path.join(androidProject, "tauri.settings.gradle");
  const appBuildPath = path.join(androidProject, "app", "tauri.build.gradle.kts");
  const metadata = JSON.parse(
    execFileSync(
      "cargo",
      ["metadata", "--locked", "--offline", "--filter-platform", "aarch64-linux-android", "--format-version", "1", "--manifest-path", "src-tauri/Cargo.toml"],
      {
        cwd: root,
        encoding: "utf8",
        maxBuffer: 64 * 1024 * 1024,
      },
    ),
  );
  const plan = planTauriAndroidGradleBridge(metadata, { appManifest });

  writeAtomicallyIfChanged(settingsPath, plan.settings);
  writeAtomicallyIfChanged(appBuildPath, plan.appBuild);
  if (
    readFileSync(settingsPath, "utf8") !== plan.settings ||
    readFileSync(appBuildPath, "utf8") !== plan.appBuild
  ) {
    throw new Error("The generated Tauri Android Gradle bridge could not be verified after writing");
  }

  for (const generatedPath of [settingsPath, appBuildPath]) {
    const relativePath = path.relative(root, generatedPath).replaceAll(path.sep, "/");
    const ignored = spawnSync("git", ["check-ignore", "--quiet", "--", relativePath], {
      cwd: root,
      stdio: "ignore",
    });
    if (ignored.status !== 0) {
      throw new Error(`Generated bridge must remain ignored by Git: ${relativePath}`);
    }
  }

  console.log(`Generated the locked Tauri ${plan.tauriVersion} Android Gradle bridge.`);
};

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main();
}
